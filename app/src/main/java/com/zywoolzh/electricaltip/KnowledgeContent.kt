package com.zywoolzh.electricaltip

data class KnowledgeTip(
    val id: String,
    val category: String,
    val title: String,
    val summary: String,
    val body: String,
    val source: String = "原理学习笔记（非规范原文）",
    val favorite: Boolean = false,
) {
    fun validate() {
        require(id.matches(Regex("[A-Za-z0-9_-]{1,80}"))) { "编号限 1—80 位字母、数字、短横线或下划线" }
        require(category.isNotBlank() && category.length <= 30) { "分类不能为空且不超过 30 字" }
        require(title.isNotBlank() && title.length <= 80) { "标题不能为空且不超过 80 字" }
        require(summary.isNotBlank() && summary.length <= 2000) { "卡片摘要不能为空且不超过 2000 字" }
        require(body.isNotBlank() && body.length <= 20000) { "正文不能为空且不超过 20000 字" }
        require(source.length <= 500) { "来源不超过 500 字" }
    }
}

