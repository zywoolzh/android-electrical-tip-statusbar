object IntervalCalculator {
    fun toMillis(value: Int, unit: IntervalUnit): Long =
        value.coerceIn(1, 365).toLong() * (if (unit == IntervalUnit.DAYS) 24 else 1) * 3_600_000L
}
enum class IntervalUnit { HOURS, DAYS }
